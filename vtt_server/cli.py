"""``vtt-server``: run the VTT Transcribe server (API and web UI) from the installed package.

    vtt-server init                 write a .env with freshly generated secrets
    vtt-server [run] [--port 8000]  start the server (the default command)

Settings come from the environment (a ``.env`` in the current directory is read too, without overriding variables that
are already set); the options below override them. The secrets are never defaulted: without ``SECRET_KEY`` and
``ENCRYPTION_KEY`` the server refuses to start and says how to create them.
"""

from __future__ import annotations

import argparse
import os
import secrets
import stat
import sys
from pathlib import Path

REQUIRED_SECRETS = ("SECRET_KEY", "ENCRYPTION_KEY")


def _version() -> str:
    from vtt_server._version import __version__

    return __version__


def default_data_dir() -> Path:
    """Where the database, uploaded audio and models live unless told otherwise (XDG data home)."""
    base = os.environ.get("XDG_DATA_HOME") or str(Path.home() / ".local" / "share")
    return Path(base) / "vtt-transcribe-server"


def load_env_file(path: Path) -> None:
    """Read ``KEY=VALUE`` lines into the environment; variables that are already set win."""
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.removeprefix("export ").strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        os.environ.setdefault(key, value)


def new_secrets() -> dict[str, str]:
    from cryptography.fernet import Fernet

    return {
        "SECRET_KEY": secrets.token_hex(32),
        "ENCRYPTION_KEY": Fernet.generate_key().decode(),
        "SESSION_SECRET": secrets.token_hex(32),
    }


def init_command(args: argparse.Namespace) -> int:
    target = Path(args.env_file)
    if target.exists() and not args.force:
        print(f"{target} already exists; not overwriting it (use --force to replace it).", file=sys.stderr)
        return 1
    generated = new_secrets()
    body = (
        "# Generated by `vtt-server init`. Keep this file private (it is created readable by you only).\n"
        "# Changing ENCRYPTION_KEY later makes stored API keys unreadable; changing SECRET_KEY signs everyone out.\n"
        f"SECRET_KEY={generated['SECRET_KEY']}\n"
        f"ENCRYPTION_KEY={generated['ENCRYPTION_KEY']}\n"
        f"SESSION_SECRET={generated['SESSION_SECRET']}\n"
        "\n"
        "# Optional (see the README for the full list):\n"
        "# VTT_DEFAULT_RETENTION_DAYS=7\n"
        "# VTT_PUBLIC_URL=https://vtt.example.com\n"
        "# SMTP_HOST=smtp.example.com\n"
    )
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, stat.S_IRUSR | stat.S_IWUSR)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(body)
    target.chmod(stat.S_IRUSR | stat.S_IWUSR)
    print(f"Wrote {target} with new SECRET_KEY, ENCRYPTION_KEY and SESSION_SECRET.")
    print("Start the server with:  vtt-server")
    return 0


def missing_secrets() -> list[str]:
    missing = [name for name in REQUIRED_SECRETS if not os.environ.get(name)]
    # SECRET_KEY has an explicit, loudly named development escape hatch in the app itself.
    if "SECRET_KEY" in missing and os.environ.get("VTT_TRANSCRIBE_DEV_MODE", "").lower() in {"1", "true", "yes"}:
        missing.remove("SECRET_KEY")
    return missing


def run_command(args: argparse.Namespace) -> int:
    env_file = Path(args.env_file) if args.env_file else Path(".env")
    if env_file.is_file():
        load_env_file(env_file)
    elif args.env_file:
        print(f"Env file not found: {env_file}", file=sys.stderr)
        return 1

    missing = missing_secrets()
    if missing:
        print(f"Missing required setting(s): {', '.join(missing)}\n", file=sys.stderr)
        print("Create them with:\n  vtt-server init          # writes ./.env with fresh secrets\n", file=sys.stderr)
        print(
            "or set them yourself:\n"
            "  export SECRET_KEY=$(python -c 'import secrets; print(secrets.token_hex(32))')\n"
            "  export ENCRYPTION_KEY=$(python -c 'from cryptography.fernet import Fernet; "
            "print(Fernet.generate_key().decode())')",
            file=sys.stderr,
        )
        return 2

    data_dir = Path(args.data_dir or os.environ.get("VTT_SERVER_DATA_DIR") or default_data_dir()).expanduser().resolve()
    jobs_dir = Path(os.environ.get("VTT_DATA_DIR") or data_dir / "jobs")
    if args.data_dir:  # an explicit option wins over the environment
        jobs_dir = data_dir / "jobs"
        os.environ["VTT_MODEL_DIR"] = str(data_dir / "models")
    os.environ.setdefault("VTT_MODEL_DIR", str(data_dir / "models"))
    os.environ["VTT_DATA_DIR"] = str(jobs_dir)
    for directory in (data_dir, jobs_dir):
        directory.mkdir(parents=True, exist_ok=True)

    if args.database_url:
        os.environ["DATABASE_URL"] = args.database_url
    else:
        os.environ.setdefault("DATABASE_URL", f"sqlite+aiosqlite:///{data_dir / 'vtt.db'}")

    host = args.host or os.environ.get("API_HOST") or "127.0.0.1"
    port = args.port or int(os.environ.get("API_PORT") or 8000)

    import uvicorn

    ui = os.environ.get("VTT_STATIC_DIR")
    print(f"vtt-transcribe-server {_version()}  http://{host}:{port}  data: {data_dir}")
    if ui is not None and not ui:
        print("Web UI switched off (VTT_STATIC_DIR is empty).")
    # One process: the job queue runs inside it (see the README), so no --workers.
    uvicorn.run("vtt_server.app:app", host=host, port=port, log_level=args.log_level)
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="vtt-server",
        description="Run the VTT Transcribe server (API and web UI).",
        epilog="Run `vtt-server init` once to create a .env with fresh secrets.",
    )
    parser.add_argument("--version", action="version", version=f"%(prog)s {_version()}")
    sub = parser.add_subparsers(dest="command")

    init = sub.add_parser("init", help="write a .env with freshly generated SECRET_KEY and ENCRYPTION_KEY")
    init.add_argument("--env-file", default=".env", help="file to write (default: ./.env)")
    init.add_argument("--force", action="store_true", help="overwrite an existing file")

    for target in (parser, sub.add_parser("run", help="start the server (default)")):
        target.add_argument("--host", help="address to listen on (default: $API_HOST or 127.0.0.1; use 0.0.0.0 to expose it)")
        target.add_argument("--port", type=int, help="port (default: $API_PORT or 8000)")
        target.add_argument(
            "--data-dir", help="where the database, uploads and models live (default: ~/.local/share/vtt-transcribe-server)"
        )
        target.add_argument(
            "--database-url", help="SQLAlchemy URL, e.g. postgresql://user:pass@host/db (default: SQLite in the data dir)"
        )
        target.add_argument("--env-file", help="read settings from this file (default: ./.env if present)")
        target.add_argument("--log-level", default="info", choices=["critical", "error", "warning", "info", "debug"])
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.command == "init":
        return init_command(args)
    return run_command(args)


if __name__ == "__main__":
    sys.exit(main())
